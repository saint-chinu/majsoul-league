CREATE TABLE IF NOT EXISTS seating (id INTEGER PRIMARY KEY, revision INTEGER NOT NULL, body TEXT NOT NULL);
INSERT OR IGNORE INTO seating VALUES (4, 0, '[]');
CREATE TABLE IF NOT EXISTS audit (revision INTEGER PRIMARY KEY, body TEXT NOT NULL, saved_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TRIGGER IF NOT EXISTS seating_audit AFTER UPDATE ON seating BEGIN
  INSERT INTO audit(revision,body) VALUES (NEW.revision,NEW.body);
END;
